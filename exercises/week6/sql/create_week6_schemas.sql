             'PRIMARY KEY (stream_generation_id, stream_batch_id, minute_start, service, status_code)',
             'stream_generation_id, stream_batch_id, minute_start, service, status_code'),
            ('week6_log', 'requests_per_minute_stream',
             'PRIMARY KEY (stream_generation_id, stream_batch_id, minute_start, service)',
             'stream_generation_id, stream_batch_id, minute_start, service'),
            ('week6_log', 'status_distribution_stream',
             'PRIMARY KEY (stream_generation_id, stream_batch_id, minute_start, service, status_code)',
             'stream_generation_id, stream_batch_id, minute_start, service, status_code')
        ) AS definitions(schema_name, table_name, expected_definition, columns_sql)
    LOOP
        primary_key_name := NULL;
        primary_key_definition := NULL;
        SELECT constraint_name, definition
        INTO primary_key_name, primary_key_definition
        FROM (
            SELECT pk_constraint.conname AS constraint_name,
                   pg_get_constraintdef(pk_constraint.oid) AS definition
            FROM pg_constraint AS pk_constraint
            WHERE pk_constraint.conrelid = format('%I.%I', item.schema_name, item.table_name)::regclass
              AND pk_constraint.contype = 'p'
        ) AS current_primary_key;

        IF primary_key_name IS NOT NULL
           AND primary_key_definition <> item.expected_definition THEN
            EXECUTE format(
                'ALTER TABLE %I.%I DROP CONSTRAINT %I',
                item.schema_name, item.table_name, primary_key_name
            );
            primary_key_name := NULL;
        END IF;
        IF primary_key_name IS NULL THEN
            EXECUTE format(
                'ALTER TABLE %I.%I ADD PRIMARY KEY (%s)',
                item.schema_name, item.table_name, item.columns_sql
            );
        END IF;
    END LOOP;
END $$;

-- Dữ liệu epoch-only đã có được khóa vào generation migration riêng và seed
-- high-water. Checkpoint thật không thể vô tình tái dùng namespace legacy này.
INSERT INTO week6_control.log_stream_generations(
    stream_generation_id, query_name, checkpoint_path,
    last_successful_batch_id, lineage_id, is_active
)
SELECT 'legacy-v1',
       COALESCE(
           (ARRAY_AGG(query_name ORDER BY finished_at DESC NULLS LAST))[1],
           'de_genesis_week6_service_logs'
       ),
       'migration-lock://legacy-v1',
       COALESCE(
           MAX(stream_batch_id) FILTER (WHERE status='success'),
           -1
       ),
       'legacy-v1',
       FALSE
FROM week6_control.log_stream_batches
WHERE stream_generation_id='legacy-v1'
HAVING COUNT(*) > 0
ON CONFLICT (stream_generation_id) DO UPDATE
SET last_successful_batch_id=GREATEST(
        week6_control.log_stream_generations.last_successful_batch_id,
        EXCLUDED.last_successful_batch_id
    ),
    updated_at=NOW();

-- Mỗi query chỉ có một generation current. Migration chỉ dọn active trùng và
-- bootstrap generation đã từng success; generation mới chưa publish vẫn inactive.
WITH active_ranked AS (
    SELECT stream_generation_id,
           ROW_NUMBER() OVER (
               PARTITION BY query_name
               ORDER BY updated_at DESC, created_at DESC, stream_generation_id DESC
           ) AS active_rank
    FROM week6_control.log_stream_generations
    WHERE is_active
)
UPDATE week6_control.log_stream_generations AS generation
SET is_active=FALSE, updated_at=NOW()
FROM active_ranked
WHERE active_ranked.stream_generation_id=generation.stream_generation_id
  AND active_ranked.active_rank > 1;

WITH bootstrap_ranked AS (
    SELECT stream_generation_id, query_name,
           ROW_NUMBER() OVER (
               PARTITION BY query_name
               ORDER BY last_successful_batch_id DESC, updated_at DESC,
                        created_at DESC, stream_generation_id DESC
           ) AS bootstrap_rank
    FROM week6_control.log_stream_generations
    WHERE last_successful_batch_id >= 0
)
UPDATE week6_control.log_stream_generations AS generation
SET is_active=TRUE, updated_at=NOW()
FROM bootstrap_ranked
WHERE bootstrap_ranked.stream_generation_id=generation.stream_generation_id
  AND bootstrap_ranked.bootstrap_rank=1
  AND NOT EXISTS (
      SELECT 1
      FROM week6_control.log_stream_generations AS active_generation
      WHERE active_generation.query_name=bootstrap_ranked.query_name
        AND active_generation.is_active
  );

CREATE UNIQUE INDEX IF NOT EXISTS uq_week6_log_stream_active_generation
    ON week6_control.log_stream_generations(query_name)
    WHERE is_active;

CREATE OR REPLACE VIEW week6_log.live_requests_per_minute AS
SELECT minute_start,
       service,
       SUM(request_count)::BIGINT AS request_count,
       ROUND(SUM(latency_sum_ms) / NULLIF(SUM(request_count), 0), 3) AS avg_latency_ms,
       MAX(max_latency_ms) AS max_latency_ms
FROM week6_log.requests_per_minute_stream AS report
JOIN week6_control.log_stream_generations AS generation
  ON generation.stream_generation_id=report.stream_generation_id
JOIN week6_control.log_stream_generations AS active_generation
  ON active_generation.query_name=generation.query_name
 AND active_generation.lineage_id=generation.lineage_id
 AND active_generation.is_active
GROUP BY minute_start, service;

CREATE OR REPLACE VIEW week6_log.live_status_distribution AS
WITH counts AS (
    SELECT minute_start,
           service,
           status_code,
           SUM(request_count)::BIGINT AS request_count
    FROM week6_log.status_distribution_stream AS report
    JOIN week6_control.log_stream_generations AS generation
      ON generation.stream_generation_id=report.stream_generation_id
    JOIN week6_control.log_stream_generations AS active_generation
      ON active_generation.query_name=generation.query_name
     AND active_generation.lineage_id=generation.lineage_id
     AND active_generation.is_active
    GROUP BY minute_start, service, status_code
)
SELECT minute_start,
       service,
       status_code,
       request_count,
       ROUND(
           request_count * 100.0
           / NULLIF(SUM(request_count) OVER (PARTITION BY minute_start, service), 0),
           3
       ) AS percentage
FROM counts;


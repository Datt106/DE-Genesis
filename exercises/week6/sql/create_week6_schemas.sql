DECLARE
    item RECORD;
    primary_key_name TEXT;
    primary_key_definition TEXT;
BEGIN
    FOR item IN
        SELECT * FROM (VALUES
            ('week6_control', 'log_stream_batches',
             'PRIMARY KEY (stream_generation_id, stream_batch_id)',
             'stream_generation_id, stream_batch_id'),
